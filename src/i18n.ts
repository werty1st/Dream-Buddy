export const LANGS = { de: "Deutsch", en: "English", es: "Español", fr: "Français", it: "Italiano" };
export type Lang = keyof typeof LANGS;
export type Key = keyof typeof de;
const DICTS: Record<Lang, Dict> = { de, en, es, fr, it };

const isLang = (l: string | null | undefined): l is Lang => !!l && l in LANGS;

function detect(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (isLang(saved)) return saved;
  } catch {
    /* kein Storage */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const short = l.slice(0, 2).toLowerCase();
    if (isLang(short)) return short;
  }
  return "en";
}

export let lang: Lang = detect();

export const t = (key: Key, vars: Record<string, string | number> = {}) =>
  DICTS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem("lang", l);
  } catch {
    /* kein Storage */
  }
}
